import { createHash } from 'node:crypto';
import { toZod, type JsonSchema, type ZodContext } from './jsonSchemaToZod.ts';

const HTTP_METHODS = ['get', 'post', 'put', 'patch', 'delete'] as const;
export type HttpMethod = (typeof HTTP_METHODS)[number];
const JSON_CONTENT = 'application/json';
const API_PREFIX = /^\/[^/]+\/v1\//; // the namespace of this app (`/admin/v1`, `/parent-web/v1`, ...)
const PATH_PARAM = /^\{(.+)\}$/;
const SUCCESS_STATUS = /^2\d\d$/;
export const SHA_MARKER = 'source-sha256:';

interface SpecParameter {
  name: string;
  in: 'query' | 'path' | 'header';
  required?: boolean;
  schema: JsonSchema;
}

interface SpecResponse {
  content?: Record<string, { schema: JsonSchema }>;
}

interface SpecOperation {
  tags?: string[];
  summary?: string;
  parameters?: SpecParameter[];
  requestBody?: { content: Record<string, { schema: JsonSchema }> };
  responses: Record<string, SpecResponse>;
}

export interface Spec {
  paths: Record<string, Partial<Record<HttpMethod, SpecOperation>>>;
  components?: { schemas?: Record<string, JsonSchema> };
}

export interface OperationInfo {
  id: string;
  method: HttpMethod;
  path: string;
  tag: string;
  summary: string;
  status: number;
  hasBody: boolean;
  hasQuery: boolean;
  hasMeta: boolean;
}

const pascal = (text: string) =>
  text
    .split(/[^A-Za-z0-9]+/)
    .filter(Boolean)
    .map((word) => word.charAt(0).toUpperCase() + word.slice(1))
    .join('');

/** `POST /admin/v1/auth/login` -> `postAuthLogin`; `GET .../items/{id}` -> `getItemsById`. */
export function operationId(method: HttpMethod, path: string): string {
  const parts = path.replace(API_PREFIX, '').split('/').filter(Boolean);
  const name = parts
    .map((part) => {
      const param = PATH_PARAM.exec(part)?.[1];
      return param ? `By${pascal(param)}` : pascal(part);
    })
    .join('');
  return `${method}${name}`;
}

export const sha256 = (text: string): string => createHash('sha256').update(text).digest('hex');

function jsonSchemaOf(content: Record<string, { schema: JsonSchema }> | undefined) {
  return content?.[JSON_CONTENT]?.schema;
}

function successOf(op: SpecOperation): { status: number; envelope: JsonSchema } | undefined {
  const status = Object.keys(op.responses).find((code) => SUCCESS_STATUS.test(code));
  const envelope = status ? jsonSchemaOf(op.responses[status]?.content) : undefined;
  return status && envelope ? { status: Number(status), envelope } : undefined;
}

function queryObject(op: SpecOperation): JsonSchema | undefined {
  const query = (op.parameters ?? []).filter((p) => p.in === 'query');
  if (query.length === 0) return undefined;
  return {
    type: 'object',
    properties: Object.fromEntries(query.map((p) => [p.name, p.schema])),
    required: query.filter((p) => p.required).map((p) => p.name),
  };
}

export interface ContractOperation {
  info: OperationInfo;
  body?: JsonSchema;
  query?: JsonSchema;
  data?: JsonSchema;
}

/** Reads every operation of the spec; throws when two operations get the same id or a success has no JSON body. */
export function readOperations(spec: Spec): ContractOperation[] {
  const seen = new Set<string>();
  const out: ContractOperation[] = [];
  for (const [path, item] of Object.entries(spec.paths)) {
    for (const method of HTTP_METHODS) {
      const op = item[method];
      if (!op) continue;
      const id = operationId(method, path);
      if (seen.has(id)) throw new Error(`Duplicate operation id "${id}"`);
      seen.add(id);
      const success = successOf(op);
      if (!success) throw new Error(`${method.toUpperCase()} ${path} has no JSON success response`);
      const props = success.envelope.properties ?? {};
      const body = jsonSchemaOf(op.requestBody?.content);
      const query = queryObject(op);
      out.push({
        info: {
          id,
          method,
          path,
          tag: op.tags?.[0] ?? '',
          summary: op.summary ?? '',
          status: success.status,
          hasBody: body !== undefined,
          hasQuery: query !== undefined,
          hasMeta: props['meta'] !== undefined && props['data']?.type === 'array',
        },
        body,
        query,
        data: props['data'],
      });
    }
  }
  return out;
}

const COMPONENT_PREFIX = 'components';
const ctx: ZodContext = { componentRef: (name) => `${COMPONENT_PREFIX}.${name}()` };

const header = (sha: string, what: string) =>
  `// GENERATED by \`npm run api:sync\` from __SERVER_DIR__/docs/api/openapi.admin.json - do not edit.\n// ${SHA_MARKER} ${sha}\n// ${what}\n`;

/** Zod factories (lazy, so unused ones are tree-shaken) and inferred types for every operation. */
export function renderDto(spec: Spec, sha: string): string {
  const lines = [header(sha, 'DTO schemas'), "import { z } from 'zod';", ''];
  lines.push(`export const ${COMPONENT_PREFIX} = {`);
  for (const [name, schema] of Object.entries(spec.components?.schemas ?? {})) {
    lines.push(`  ${name}: () => ${toZod(schema, ctx)},`);
  }
  lines.push('};', '');
  const types: string[] = [];
  for (const { info, body, query, data } of readOperations(spec)) {
    const parts: Array<[string, JsonSchema | undefined]> = [
      ['Body', body],
      ['Query', query],
      ['Data', data],
    ];
    for (const [suffix, schema] of parts) {
      if (!schema) continue;
      const name = `${info.id}${suffix}`;
      lines.push(`export const ${name}Schema = () => ${toZod(schema, ctx)};`);
      types.push(`export type ${name} = z.infer<ReturnType<typeof ${name}Schema>>;`);
    }
  }
  return `${[...lines, '', ...types].join('\n')}\n`;
}

/** Operation metadata (method, path, tag, flags) for the endpoint registry and the API-consumption doc. */
export function renderOperations(spec: Spec, sha: string): string {
  const rows = readOperations(spec).map(
    ({ info }) => `  ${JSON.stringify(info.id)}: ${JSON.stringify(info)},`,
  );
  return [
    header(sha, 'Operation metadata'),
    "import type { OperationInfo } from '../operationInfo';",
    '',
    'export const OPERATIONS = {',
    ...rows,
    '} as const satisfies Record<string, OperationInfo>;',
    '',
    'export type OperationId = keyof typeof OPERATIONS;',
    '',
  ].join('\n');
}
