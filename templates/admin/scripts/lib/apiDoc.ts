import type { OperationInfo } from './contract.ts';

export const API_DOC_FILE = 'docs/API_CONSUMED.md';
export const API_EXEMPTIONS_FILE = 'scripts/api-exemptions.json';
/** The server's base path is not part of the planning table in the backlog. */
const API_PREFIX = '/admin/v1';

/** `GET /alerts/{id}` -> tasks planned for it, read from the backlog's Appendix A table. */
export function parseAppendixA(markdown: string): Map<string, string[]> {
  const out = new Map<string, string[]>();
  const row = /^\|\s*`([A-Z]+) ([^`]+)`\s*\|[^|]*\|\s*([^|]*?)\s*\|\s*$/gm;
  for (const m of markdown.matchAll(row)) {
    const tasks = (m[3] ?? '').match(/ADM-\d{3}[a-z]?/g) ?? [];
    out.set(`${m[1] ?? ''} ${m[2] ?? ''}`, tasks);
  }
  return out;
}

/** Source files that name `OPERATIONS.<id>`: the code that really consumes an operation. */
export function findConsumers(
  files: ReadonlyArray<{ path: string; text: string }>,
): Map<string, string[]> {
  const out = new Map<string, string[]>();
  for (const { path, text } of files)
    for (const m of text.matchAll(/OPERATIONS\.([A-Za-z0-9_]+)/g)) {
      const id = m[1] ?? '';
      const list = out.get(id) ?? [];
      if (!list.includes(path)) out.set(id, [...list, path].sort());
    }
  return out;
}

export interface ApiDocInput {
  operations: readonly OperationInfo[];
  appendixA: ReadonlyMap<string, readonly string[]>;
  consumers: ReadonlyMap<string, readonly string[]>;
  /** operation id -> reason it needs no consumer */
  exemptions: Readonly<Record<string, string>>;
}

export interface ApiDoc {
  markdown: string;
  problems: string[];
}

const cell = (text: string): string => text.replace(/\|/g, '\\|');

/** Builds `docs/API_CONSUMED.md` and the list of problems (an operation nobody plans to use, or a stale exemption). */
export function buildApiDoc({ operations, appendixA, consumers, exemptions }: ApiDocInput): ApiDoc {
  const problems: string[] = [];
  const rows = [...operations]
    .sort((a, b) => a.path.localeCompare(b.path) || a.method.localeCompare(b.method))
    .map((op) => {
      const key = `${op.method.toUpperCase()} ${op.path.startsWith(API_PREFIX) ? op.path.slice(API_PREFIX.length) : op.path}`;
      const tasks = appendixA.get(key) ?? [];
      const files = consumers.get(op.id) ?? [];
      const exempt = exemptions[op.id];
      if (tasks.length === 0 && files.length === 0 && !exempt)
        problems.push(
          `${key} (${op.id}) has no consuming task, no consumer in code and no exemption`,
        );
      const status = files.length > 0 ? 'Implemented' : exempt ? 'Exempt' : 'Planned';
      const who = exempt && files.length === 0 ? `exempt: ${exempt}` : tasks.join(', ');
      return `| \`${key}\` | \`${op.id}\` | ${cell(who)} | ${files.map((f) => `\`${f}\``).join('<br>')} | ${status} |`;
    });
  for (const id of Object.keys(exemptions))
    if (!operations.some((o) => o.id === id)) problems.push(`exemption "${id}" names no operation`);
  const implemented = rows.filter((r) => r.endsWith('| Implemented |')).length;
  const markdown = [
    '# Admin API consumed by the panel',
    '',
    '> GENERATED by `npm run docs:api` from the contract snapshot, the backlog (Appendix A) and the code. Do not edit.',
    `> ${String(operations.length)} operations: ${String(implemented)} implemented, ${String(rows.length - implemented)} planned or exempt.`,
    '',
    '| Operation | Id | Planned in task | Implemented in | Status |',
    '|---|---|---|---|---|',
    ...rows,
    '',
  ].join('\n');
  return { markdown, problems };
}
