"""Root workspace of the generated repo: `.claude/projects.json`, the per-project files every chosen project needs on
day one (CLAUDE.md, backlog, session, memory, Integration — from `docs/templates/*_TEMPLATE.md` when the workspace
template ships them), the knowledge folder, `tasks.py check`, `git init` + first commit + master branches, next steps."""
from __future__ import annotations

import json
import re
import shutil
import subprocess
from pathlib import Path
from typing import Dict, List, Optional, Tuple

from prompts import FIXED_PREFIXES, Spec

REGISTRY_REL = Path(".claude") / "projects.json"
DOC_TEMPLATES_REL = Path("docs") / "templates"
KNOWLEDGE_REL = Path("docs") / "knowledge"
PROJECT_FILE_KEYS = ("claude", "backlog", "session", "memory", "integration")
DOC_TEMPLATE_NAMES = {"claude": "PROJECT_CLAUDE_TEMPLATE.md", "backlog": "TASKS_TEMPLATE.md",
                      "session": "PROJECT_SESSION_TEMPLATE.md", "memory": "PROJECT_MEMORY_TEMPLATE.md",
                      "integration": "PROJECT_INTEGRATION_TEMPLATE.md"}
STAGE_HEADING_RE = re.compile(r"^## Stage ", re.M)
TASKS_TOOL_REL = Path("scripts") / "tasks.py"
BOARD_FILE = "INTEGRATION.md"
STATUSES = ["TODO", "IN PROGRESS", "IN REVIEW", "DONE", "PENDING", "BLOCKED", "CANCELLED"]
OWNER_INPUT_MARKERS = ["user input", "owner input", "owner decision"]
SCAFFOLD_STATUS = "scaffold (generated by SYSTEM_SETUP)"
PROJECTS_JSON_INDENT = "  "  # `"projects": __PROJECTS_JSON__` sits one level deep in the template file
BACKLOG_HEADER = "| ID | Task | Branch | Needs | Status | Sources / notes |\n|---|---|---|---|---|---|\n"
GATE_COMMANDS = {
    "server": "npm run verify",
    "admin": "sh scripts/gate.sh",
    "app": "scripts/ci/run_local_checks.sh",
    "sdk": "npm run verify",
}
INSTALL_COMMANDS = {
    "server": "npm install",
    "admin": "npm install",
    "app": "./gradlew tasks (Android Studio / Xcode open the hosts)",
    "sdk": "npm install",
}


def project_entry(title: str, kind: str, prefix: str, directory: str, master: str, backlog_name: str) -> Dict[str, str]:
    return {
        "title": title,
        "kind": kind,
        "prefix": prefix,
        "dir": directory,
        "master": master,
        "backlog": f"{directory}/docs/{backlog_name}",
        "session": f"{directory}/.claude/session.md",
        "memory": f"{directory}/.claude/memory.md",
        "integration": f"{directory}/.claude/Integration.md",
    }


def projects_registry(spec: Spec) -> Dict[str, object]:
    """`.claude/projects.json` in the exact shape `tasks.py` reads."""
    projects: Dict[str, Dict[str, str]] = {}
    if spec.with_server:
        projects["server"] = project_entry(f"{spec.server_dir} (backend API)", "server", FIXED_PREFIXES["server"], spec.server_dir,
                                           "server", f"{spec.prefix}_Server_Tasks.md")
    if spec.with_admin:
        projects["admin"] = project_entry(f"{spec.admin_dir} (web panel)", "web", FIXED_PREFIXES["admin"], spec.admin_dir,
                                          "admin", f"{spec.prefix}_Admin_Tasks.md")
    prefixes = spec.app_prefixes()
    for app in spec.apps:
        projects[app.slug] = project_entry(f"{spec.app_dir(app)} (KMP app)", "kmp", prefixes[app.slug], spec.app_dir(app),
                                           app.slug, f"{spec.prefix}_{app.project}_Tasks.md")
    for sdk in spec.sdks:
        projects[sdk] = project_entry(f"{spec.sdk_dir(sdk)} (SDK)", "sdk", spec.sdk_prefix(sdk), spec.sdk_dir(sdk), "server",
                                      f"{spec.prefix}_Package_{spec.sdk_title_of(sdk)}_Tasks.md")
    return {
        "_comment": "Registry of every project and SDK in the monorepo. Read by scripts/tasks.py (backlog queries, "
                    "status propagation, INTEGRATION.md board). Paths are relative to the repo root.",
        "board_file": BOARD_FILE,
        "statuses": STATUSES,
        "owner_input_markers": OWNER_INPUT_MARKERS,
        "projects": projects,
    }


def workspace_values(spec: Spec, registry: Dict[str, object]) -> Dict[str, str]:
    """Engine-computed workspace tokens: the repository-map rows and the `projects` object of projects.json."""
    projects: Dict[str, Dict[str, str]] = registry["projects"]  # type: ignore[assignment]
    app_rows = [f"| `{spec.app_dir(app)}/` | {app.name} app (KMP + Compose Multiplatform, `{spec.app_package(app)}`, "
                f"tasks `{projects[app.slug]['prefix']}`, master `{app.slug}`) | {SCAFFOLD_STATUS} |" for app in spec.apps]
    sdk_rows = [f"| `{spec.sdk_dir(sdk)}/` | SDK `{spec.sdk_package(sdk)}` (ports + adapters, tasks `{projects[sdk]['prefix']}`, "
                f"master `server`) | {SCAFFOLD_STATUS} |" for sdk in spec.sdks]
    projects_json = json.dumps(projects, indent=2, ensure_ascii=False).replace("\n", "\n" + PROJECTS_JSON_INDENT)
    return {"__APPS_TABLE__": "\n".join(app_rows), "__SDKS_TABLE__": "\n".join(sdk_rows), "__PROJECTS_JSON__": projects_json}


def projects_table(registry: Dict[str, object]) -> str:
    """Markdown rows `| key | folder | prefix | master | backlog |` of every project (for the agent prompt)."""
    projects: Dict[str, Dict[str, str]] = registry["projects"]  # type: ignore[assignment]
    rows = ["| Project key | Folder | Task prefix | Master | Backlog |", "|---|---|---|---|---|"]
    rows.extend(f"| `{name}` | `{p['dir']}/` | `{p['prefix']}` | `{p['master']}` | `{p['backlog']}` |" for name, p in projects.items())
    return "\n".join(rows)


def registry_shipped(repo_root: Path, registry: Dict[str, object]) -> bool:
    """True when the workspace template already rendered a projects.json with the same projects (via __PROJECTS_JSON__)."""
    path = repo_root / REGISTRY_REL
    if not path.is_file():
        return False
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
    except (json.JSONDecodeError, OSError):
        return False
    return isinstance(data, dict) and data.get("projects") == registry["projects"]


def write_registry(repo_root: Path, registry: Dict[str, object]) -> Path:
    path = repo_root / REGISTRY_REL
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(registry, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    return path


def first_rows(project: Dict[str, str]) -> str:
    """Stage A of a new backlog: rows `tasks.py check` accepts on day one (no dependency on another project)."""
    prefix, lower = project["prefix"], project["prefix"].lower()
    return ("## Stage A — Foundation\n" + BACKLOG_HEADER
            + f"| {prefix}-001 | Project scaffold: install, gate green, first commit | `feat/{lower}-001-scaffold` | — | TODO | project `CLAUDE.md` §1; no ops |\n"
            + f"| {prefix}-002 | Config loader and env schema (`.env.example` enforced by a test) | `feat/{lower}-002-config` | {prefix}-001 | TODO | no ops |\n")


def starter_backlog(name: str, project: Dict[str, str]) -> str:
    return (f"# {project['dir']} — Task Backlog\n\n"
            f"> One task = one branch = one PR into `{project['master']}`. Next task: `python3 scripts/tasks.py next {name}`. "
            f"Statuses: {' · '.join(f'`{s}`' for s in STATUSES)}.\n\n" + first_rows(project))


def starter_claude(project: Dict[str, str]) -> str:
    return (f"# {project['dir']} — Rules for AI Agents (loaded only inside this folder)\n\n"
            "> Root `CLAUDE.md` and `.claude/*` are auto-loaded; this file adds the project's stack, gate command, "
            "architecture layers and conventions. It never relaxes a root rule.\n")


def render_project_doc(text: str, name: str, project: Dict[str, str]) -> str:
    """Fills the `<Project>`, `<PREFIX>`, `XXX`, `<master>` markers of a `docs/templates/*_TEMPLATE.md` file."""
    prefix = project["prefix"]
    for marker, value in (("<Project>", project["dir"]), ("<project>", name), ("<PREFIX>", prefix), ("<prefix>", prefix.lower()),
                          ("XXX", prefix), ("xxx", prefix.lower()), ("<master>", project["master"])):
        text = text.replace(marker, value)
    return text


def project_file_content(repo_root: Path, key: str, name: str, project: Dict[str, str]) -> str:
    """The workspace template's doc template when it ships one, else the built-in starter."""
    template = repo_root / DOC_TEMPLATES_REL / DOC_TEMPLATE_NAMES[key]
    starters = {"claude": lambda: starter_claude(project), "backlog": lambda: starter_backlog(name, project),
                "session": lambda: starter_session(name, project), "memory": lambda: starter_memory(project),
                "integration": lambda: starter_integration(project)}
    if not template.is_file():
        return starters[key]()
    text = render_project_doc(template.read_text(encoding="utf-8"), name, project)
    if key == "backlog":
        # Keep the template's prose (purpose, writing rules); its example rows name other projects' ids, which
        # `tasks.py check` would reject, so the first real rows are generated instead.
        match = STAGE_HEADING_RE.search(text)
        text = (text[:match.start()] if match else text.rstrip() + "\n\n") + first_rows(project)
    return text


def starter_session(name: str, project: Dict[str, str]) -> str:
    return (f"# {project['dir']} — Session\n\n"
            f"> Loaded on every turn while working in this folder. Keep the current task block + the last 2 blocks. "
            f"Next task: `python3 scripts/tasks.py next {name}`. Status changes: `tasks.py set <ID> <STATUS>`.\n\n"
            "## Current task\n\n(none)\n")


def starter_memory(project: Dict[str, str]) -> str:
    return f"# {project['dir']} — Memory (durable facts only; keep short, replace instead of append)\n\n- (none yet)\n"


def starter_integration(project: Dict[str, str]) -> str:
    return (f"# {project['dir']} — Integration\n\n"
            "> What this project exposes to and needs from the other projects. Cross-project map: root `INTEGRATION.md`.\n")


def ensure_project_files(repo_root: Path, registry: Dict[str, object]) -> List[str]:
    """Creates CLAUDE.md, backlog, session, memory and Integration for every project whose template did not ship
    them (from `docs/templates/*_TEMPLATE.md` when present), so `tasks.py check/board/next` work on day one."""
    created = []
    projects: Dict[str, Dict[str, str]] = registry["projects"]  # type: ignore[assignment]
    for name, project in projects.items():
        for key in PROJECT_FILE_KEYS:
            rel = f"{project['dir']}/CLAUDE.md" if key == "claude" else project[key]
            path = repo_root / rel
            if not path.exists():
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(project_file_content(repo_root, key, name, project), encoding="utf-8")
                created.append(rel)
    return created


def copy_knowledge(repo_root: Path, knowledge_dir: Optional[Path]) -> List[str]:
    """Copies the tool's `knowledge/*.md` (lessons, playbooks) to `docs/knowledge/` and links it from the README."""
    if knowledge_dir is None or not knowledge_dir.is_dir():
        return []
    copied = []
    target = repo_root / KNOWLEDGE_REL
    for source in sorted(knowledge_dir.glob("*.md")):
        target.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(source, target / source.name)
        copied.append(f"{KNOWLEDGE_REL.as_posix()}/{source.name}")
    readme = repo_root / "README.md"
    if copied and readme.is_file() and KNOWLEDGE_REL.as_posix() not in readme.read_text(encoding="utf-8"):
        links = ", ".join(f"[`{Path(rel).name}`]({rel})" for rel in copied)
        with readme.open("a", encoding="utf-8") as handle:
            handle.write(f"\n## Knowledge from the system this workspace was learned from\n{links} — lessons and playbooks "
                         "(start a task, ship a task, batch-verify, sync masters, local QA stack, end-to-end pass, adding a project). "
                         "Read the playbook before the first task of each kind.\n")
    return copied


def run_tasks_check(repo_root: Path) -> Tuple[Optional[bool], str]:
    """(True/False, output) after `python3 scripts/tasks.py check`; (None, reason) when the tool is missing."""
    tool = repo_root / TASKS_TOOL_REL
    if not tool.is_file():
        return None, f"{TASKS_TOOL_REL} not found (the workspace template should ship it)"
    completed = subprocess.run(["python3", str(tool), "check"], cwd=repo_root, capture_output=True, text=True, check=False)
    return completed.returncode == 0, (completed.stdout + completed.stderr).strip()


def git_init(repo_root: Path, message: str, masters: Optional[List[str]] = None) -> Optional[str]:
    """`git init` + first commit on `main`, then one local master branch per project (`server`, `admin`, `<app>`);
    returns an error text when git is missing or a step fails."""
    if shutil.which("git") is None:
        return "git not found; run `git init` yourself"
    identity = []
    if subprocess.run(["git", "config", "user.email"], cwd=repo_root, capture_output=True, check=False).returncode != 0:
        identity = ["-c", "user.name=SYSTEM_SETUP", "-c", "user.email=system-setup@localhost"]
    steps = [["git", "init", "-q", "-b", "main"], ["git", "add", "-A"], ["git", *identity, "commit", "-q", "-m", message]]
    steps.extend(["git", "branch", master, "main"] for master in (masters or []) if master != "main")
    for step in steps:
        completed = subprocess.run(step, cwd=repo_root, capture_output=True, text=True, check=False)
        if completed.returncode != 0:
            return f"`{' '.join(step)}` failed: {(completed.stderr or completed.stdout).strip()}"
    return None


def next_steps(spec: Spec, registry: Dict[str, object], git_done: bool = True, documents: bool = False) -> List[str]:
    masters = spec.masters()
    repo = f"git@github.com:{spec.owner_github}/{spec.repo_name or spec.slug}.git"
    lines = [f"cd {spec.target}"]
    if git_done:
        lines.append(f"Local branches ready: main + masters {', '.join(masters)} (SDKs share `server`). Push them: "
                     f"`git remote add origin {repo} && git push -u origin main {' '.join(masters)}`")
    else:
        lines.append(f"git init -b main && git add -A && git commit -m 'first commit' && " + " && ".join(f"git branch {m}" for m in masters))
    lines.append("Protect `main` and every master on GitHub (PRs only, no force push); PRs target the project's master, "
                 "the owner merges masters into main.")
    projects: Dict[str, Dict[str, str]] = registry["projects"]  # type: ignore[assignment]
    for name, project in projects.items():
        kind = "server" if name == "server" else "admin" if name == "admin" else "sdk" if name in spec.sdks else "app"
        lines.append(f"{project['dir']}: install `{INSTALL_COMMANDS[kind]}` · gate `{GATE_COMMANDS[kind]}` · "
                     f"first task `python3 scripts/tasks.py next {name}` then `tasks.py set {project['prefix']}-001 \"IN PROGRESS\"`")
    if documents:
        lines.append("Give docs/AGENT_PROMPT.md to your AI agent: the tool already wrote BUSINESS_DOMAIN.md, the BRD/PRD/Design Script and backlog "
                     "of every module, INTEGRATION.md and the starting API drafts; the agent reviews them, resolves the PENDING rows with you, "
                     "then starts with `python3 scripts/tasks.py next <project>`.")
    else:
        lines.append("Give docs/AGENT_PROMPT.md to your AI agent: it fills the TBD answers of BUSINESS_DOMAIN.md with the owner, "
                     "writes the PRDs/BRDs and every backlog from the business domain, then works task by task.")
    lines.append("Read CLAUDE.md and .claude/rules.md at the root before the first task; the hooks in .claude/settings.json "
                 "enforce branching, tests and the review.")
    return lines
